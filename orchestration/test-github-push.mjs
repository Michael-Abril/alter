/**
 * Test GitHub Push Integration
 * Tests the GitHub push flow with dry-run mode
 * 
 * Usage:
 *   node orchestration/test-github-push.mjs --dry-run
 *   node orchestration/test-github-push.mjs --project-id=PROJECT_ID --dry-run
 */

import 'dotenv/config';
import { PrismaClient } from '@prisma/client';
import { pushToGitHub, generatePRBody } from './github-push.mjs';
import { loadGitHubConfig } from '../src/lib/github.ts';

const db = new PrismaClient();

async function main() {
  const args = process.argv.slice(2);
  const dryRun = args.includes('--dry-run');
  const projectIdArg = args.find(a => a.startsWith('--project-id='));
  const projectId = projectIdArg ? projectIdArg.split('=')[1] : null;

  console.log('━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━');
  console.log('🧪 Testing GitHub Push Integration');
  console.log('━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━');
  console.log(`Mode: ${dryRun ? 'DRY RUN' : 'LIVE'}`);
  console.log('');

  try {
    // Find a code_build project
    let project;
    
    if (projectId) {
      project = await db.project.findUnique({
        where: { id: projectId },
        include: { user: true },
      });
    } else {
      project = await db.project.findFirst({
        where: {
          status: 'in_progress',
        },
        include: { user: true },
      });
      
      // Filter to code_build
      if (project) {
        const context = JSON.parse(project.context || '{}');
        if (context.classification !== 'code_build') {
          // Try to find a code_build project
          const allProjects = await db.project.findMany({
            where: { status: 'in_progress' },
            include: { user: true },
          });
          
          for (const p of allProjects) {
            const ctx = JSON.parse(p.context || '{}');
            if (ctx.classification === 'code_build') {
              project = p;
              break;
            }
          }
        }
      }
    }

    if (!project) {
      console.log('❌ No code_build project found');
      console.log('   Run project detection first or specify --project-id=ID');
      return;
    }

    const context = JSON.parse(project.context || '{}');
    const classification = context.classification || 'other';

    console.log('📋 Selected Project:');
    console.log(`   Name: ${project.name}`);
    console.log(`   Classification: ${classification}`);
    console.log(`   Progress: ${project.progress}%`);
    console.log(`   User ID: ${project.userId}`);
    console.log('');

    if (classification !== 'code_build') {
      console.log('⚠️  Warning: This project is not classified as code_build');
      console.log('   GitHub push only works for code projects');
      console.log('');
    }

    // Check GitHub connection
    const githubConfig = loadGitHubConfig(project.userId);
    
    if (!githubConfig || !githubConfig.token) {
      console.log('❌ GitHub not connected for this user');
      console.log('   Connect GitHub first via onboarding or API');
      return;
    }

    if (!githubConfig.defaultRepo) {
      console.log('❌ No default repository configured');
      console.log('   Set a default repo via /api/github/set-repo');
      return;
    }

    console.log('✅ GitHub Connected:');
    console.log(`   Repository: ${githubConfig.defaultOwner}/${githubConfig.defaultRepo}`);
    console.log(`   Default Branch: ${githubConfig.defaultBranch}`);
    console.log('');

    // Simulate code generation
    const mockCode = `// NightShift AI - Continued work on ${project.name}
// Generated: ${new Date().toISOString()}

export function ${project.name.replace(/[^a-zA-Z0-9]/g, '')}Component() {
  // TODO: Implement based on project requirements
  return (
    <div>
      <h1>${project.name}</h1>
      <p>This component was generated by NightShift AI</p>
    </div>
  );
}
`;

    // Determine file path
    const safeName = project.name
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '');
    const filePath = `src/nightshift/${safeName}.tsx`;

    // Generate PR details
    const commitMessage = `feat: Continue work on ${project.name}

Generated by NightShift AI continuation agent.
Progress: ${project.progress}%
Next step: ${context.nextStep || 'Continue development'}`;

    const prTitle = `NightShift: Continued work on ${project.name}`;
    const prBody = generatePRBody(
      project.name,
      project.description,
      context.nextStep || 'Continue development',
      500 // Mock token count
    );

    // Test push
    console.log('🚀 Testing GitHub Push...');
    console.log('');

    const result = await pushToGitHub({
      userId: project.userId,
      projectName: project.name,
      filePath,
      content: mockCode,
      commitMessage,
      prTitle,
      prBody,
      dryRun,
    });

    if (result.dryRun) {
      console.log('📋 DRY RUN PLAN:');
      console.log('━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━');
      console.log('');
      console.log('Repository:', result.plan.repository);
      console.log('Base Branch:', result.plan.baseBranch);
      console.log('New Branch:', result.plan.newBranch);
      console.log('');
      console.log('File Path:', result.plan.filePath);
      console.log('');
      console.log('Commit Message:');
      console.log(result.plan.commitMessage);
      console.log('');
      console.log('PR Title:', result.plan.prTitle);
      console.log('');
      console.log('PR Body:');
      console.log('─'.repeat(80));
      console.log(result.plan.prBody);
      console.log('─'.repeat(80));
      console.log('');
      console.log('Code Preview:');
      console.log('─'.repeat(80));
      console.log(result.plan.contentPreview);
      console.log('─'.repeat(80));
      console.log('');
      console.log('✅ Dry run complete - no actual changes made');
    } else {
      console.log('✅ Push Complete!');
      console.log('');
      console.log('Branch:', result.branchName);
      console.log('Repository:', result.repository);
      console.log('Pull Request:', result.prUrl);
      console.log('');
      console.log('🎉 Code has been pushed! Review the PR and merge when ready.');
    }

    console.log('');
    console.log('━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━');

  } catch (error) {
    console.error('❌ Test failed:', error);
  } finally {
    await db.$disconnect();
  }
}

main();
